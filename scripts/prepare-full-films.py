"""Prepare complete films from VIDEO for the static Show Reel page."""

import json
import re
import subprocess
from concurrent.futures import ThreadPoolExecutor
from io import BytesIO
from pathlib import Path

from PIL import Image, ImageStat

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT.parent / 'VIDEO'
OUTPUT = ROOT / 'assets/showreel-full'


def probe(path):
    return json.loads(subprocess.check_output([
        'ffprobe', '-v', 'error', '-show_entries',
        'stream=codec_type,codec_name,pix_fmt,width,height:format=duration',
        '-of', 'json', str(path),
    ]))


def order(path):
    number = re.match(r'^(\d+)', path.stem)
    return (int(number[1]) if number else 1000, path.name)


def prepare(entry):
    index, source = entry
    info = probe(source)
    duration = float(info['format']['duration'])
    video = next(s for s in info['streams'] if s['codec_type'] == 'video')
    slug = f'film-{index + 1:02}'
    target = OUTPUT / f'{slug}.mp4'
    temporary = OUTPUT / f'{slug}.partial.mp4'
    if not target.exists():
        common = ['ffmpeg', '-hide_banner', '-loglevel', 'error', '-y', '-i', str(source)]
        compatible = video['codec_name'] == 'h264' and video.get('pix_fmt') == 'yuv420p'
        compatible = compatible and all(s['codec_name'] == 'aac' for s in info['streams'] if s['codec_type'] == 'audio')
        if compatible and source.stat().st_size < 90 * 1024 * 1024:
            subprocess.run(common + ['-map', '0:v:0', '-map', '0:a:0?', '-c', 'copy',
                '-movflags', '+faststart', str(temporary)], check=True)
        else:
            # Keep long films below the per-file budget without cutting their duration.
            bitrate = min(1800, int((85 * 1024 * 1024 * 8 / duration - 128000) / 1000))
            settings = ['-map', '0:v:0', '-map', '0:a:0?', '-vf', 'scale=1280:720,setsar=1,fps=30',
                '-pix_fmt', 'yuv420p', '-b:v', f'{bitrate}k', '-maxrate', f'{bitrate}k',
                '-bufsize', f'{bitrate * 2}k', '-c:a', 'aac', '-b:a', '128k', '-movflags', '+faststart']
            try:
                subprocess.run(common + ['-c:v', 'h264_videotoolbox'] + settings + [str(temporary)], check=True)
            except subprocess.CalledProcessError:
                subprocess.run(common + ['-c:v', 'libx264', '-preset', 'fast', '-threads', '2'] + settings + [str(temporary)], check=True)
        temporary.replace(target)
    result = probe(target)
    converted = next(s for s in result['streams'] if s['codec_type'] == 'video')
    assert abs(float(result['format']['duration']) - duration) < 0.2, source.name
    poster = OUTPUT / f'{slug}-poster.webp'
    for timestamp in [5, 10, 20]:
        frame = subprocess.check_output([
            'ffmpeg', '-hide_banner', '-loglevel', 'error', '-ss', str(min(timestamp, duration / 2)),
            '-i', str(target), '-vf', 'scale=1280:-2', '-frames:v', '1', '-f', 'image2pipe', '-c:v', 'png', '-',
        ])
        thumbnail = Image.open(BytesIO(frame))
        if sum(ImageStat.Stat(thumbnail.convert('RGB')).mean) > 30:
            break
    thumbnail.save(poster, quality=82)
    print(f'Prepared full film: {source.name} ({duration:.1f}s)', flush=True)
    return {
        'original': source.name,
        'title': re.sub(r'^\d+[ .]*', '', source.stem).replace('_', ' ').strip() or source.stem,
        'src': f'/assets/showreel-full/{slug}.mp4',
        'poster': f'/assets/showreel-full/{slug}-poster.webp',
        'duration': duration,
        'width': converted['width'],
        'height': converted['height'],
    }


if __name__ == '__main__':
    OUTPUT.mkdir(parents=True, exist_ok=True)
    sources = sorted((p for p in SOURCE.iterdir() if p.suffix.lower() in {'.mp4', '.mov'}), key=order)
    with ThreadPoolExecutor(max_workers=2) as pool:
        films = list(pool.map(prepare, enumerate(sources)))
    (ROOT / 'showreel-films.js').write_text(
        '// Generated by scripts/prepare-full-films.py. Every film retains its full duration.\n'
        'export const films = ' + json.dumps(films, ensure_ascii=False, indent=2) + ';\n'
    )

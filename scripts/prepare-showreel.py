"""Prepare web videos and matching posters from the original VDO Reels folder."""

import json
from io import BytesIO
import subprocess
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCES = ROOT.parent / 'VDO Reels'
OUTPUT = ROOT / 'assets/showreel'
FILES = [
    ('Coffee First draft.mp4', 'coffee'),
    ('Cocktail First draft.mp4', 'cocktail'),
    ('Tas Pasta First draft.mp4', 'pasta'),
    ('Wine First draft.mp4', 'wine'),
    ('breakfast  First draft.mp4', 'breakfast'),
    ('Vampire grill show.MP4', 'vampire'),
    ('Izakaya ambient.mp4', 'izakaya'),
    ('Ads chill out ( no copyright music ).mp4', 'chill-out'),
    ('Picnic with chill out.mp4', 'picnic'),
    ('ขี่ม้าชมมินิซู.mp4', 'mini-zoo'),
    ('Work from Anywhere.mp4', 'work-from-anywhere'),
    ('Morph 1.mp4', 'morph'),
    ('MSN.mp4', 'msn'),
    ('Tas1 Final ( No Text ).mp4', 'tastory-1'),
    ('Tas2 ( Lesley Gore - Misty ).mp4', 'tastory-2'),
    ('Tas ADS 3 ( Can I Call You Rose ) Final .mp4', 'tastory-rose'),
    ('Tas ADS 4 ( Christmas Is You ) draft 3.mp4', 'christmas'),
    ('Tas ADS 5 ( BLUE ) Final draft.mp4', 'tastory-blue'),
    ('valentine_s day_1.mp4', 'valentine'),
    ('Mother_s day.mp4', 'mothers-day'),
    ('I Will Follow You (1963).mp4', 'i-will-follow-you'),
    ('2.MP4', 'reel-2'),
    ('TEST.mp4', 'test'),
]


def prepare(entry):
    original, slug = entry
    target = OUTPUT / f'{slug}.mp4'
    if not target.exists():
        subprocess.run([
            'ffmpeg', '-hide_banner', '-loglevel', 'error', '-y',
            '-i', str(SOURCES / original), '-vf', 'scale=720:1280,setsar=1,fps=30',
            '-c:v', 'libx264', '-preset', 'fast', '-crf', '25', '-threads', '2',
            '-pix_fmt', 'yuv420p', '-c:a', 'aac', '-b:a', '128k',
            '-movflags', '+faststart', str(target),
        ], check=True)
    frame = subprocess.check_output([
        'ffmpeg', '-hide_banner', '-loglevel', 'error', '-y', '-ss', '1',
        '-i', str(target), '-frames:v', '1', '-f', 'image2pipe', '-c:v', 'png', '-',
    ])
    Image.open(BytesIO(frame)).save(OUTPUT / f'{slug}-poster.webp', quality=82)
    print(f'Prepared {original}', flush=True)
    return {
        'original': original,
        'title': Path(original).stem.replace('_', ' '),
        'src': f'/assets/showreel/{slug}.mp4',
        'poster': f'/assets/showreel/{slug}-poster.webp',
        'width': 720,
        'height': 1280,
    }


if __name__ == '__main__':
    OUTPUT.mkdir(parents=True, exist_ok=True)
    with ThreadPoolExecutor(max_workers=3) as pool:
        reels = list(pool.map(prepare, FILES))
    (ROOT / 'showreel-media.js').write_text(
        '// Generated by scripts/prepare-showreel.py from VDO Reels.\n'
        'export const reels = ' + json.dumps(reels, ensure_ascii=False, indent=2) + ';\n\n'
        'export const reelMedia = (index) => {\n'
        '  const reel = reels[index % reels.length];\n'
        '  return { type: "video", desktop: reel.src, mobile: reel.src, tablet: reel.src,\n'
        '    posterDesktop: reel.poster, posterMobile: reel.poster, alt: reel.title };\n'
        '};\n\n'
        'export const mediaDimensions = Object.fromEntries(reels.flatMap((reel) =>\n'
        '  [[reel.src, [reel.width, reel.height]], [reel.poster, [reel.width, reel.height]]]));\n'
    )
